/* Writes test/fixtures/fixtures.g.dart from the recorded files in test/fixtures/,
   so tests on the Dart VM and in Chrome read the same bytes.
     dart run tool/fixtures_to_dart.dart            (run in studio/) */
import 'dart:convert';
import 'dart:io';

void main() {
  final out = StringBuffer('// GENERATED by tool/fixtures_to_dart.dart from test/fixtures/ — do not edit.\n')
    ..writeln('// ignore_for_file: lines_longer_than_80_chars')
    ..writeln("const solverRecorded = r'''${File('test/fixtures/solver/recorded.json').readAsStringSync()}''';")
    ..writeln("const jsMath = r'''${File('test/fixtures/solver/js-math.json').readAsStringSync()}''';")
    ..writeln("const sharma = r'''${File('test/fixtures/solver/ciede2000-sharma.tsv').readAsStringSync()}''';")
    ..writeln("const pool = r'''${File('test/fixtures/solver/pool-2026-09-11.json').readAsStringSync()}''';")
    ..writeln("const measureRecorded = r'''${File('test/fixtures/measure/recorded.json').readAsStringSync()}''';")
    ..writeln("const namedColours = r'''${File('test/fixtures/measure/named-colours.json').readAsStringSync()}''';")
    ..writeln('const pictures = <String, String>{');
  final dir = Directory('test/fixtures/measure');
  for (final f in dir.listSync().whereType<File>().where((f) => f.path.endsWith('.png') || f.path.endsWith('.jpg'))
      .toList()..sort((a, b) => a.path.compareTo(b.path))) {
    out.writeln("  '${f.uri.pathSegments.last}': '${base64Encode(f.readAsBytesSync())}',");
  }
  out.writeln('};');
  File('test/fixtures/fixtures.g.dart').writeAsStringSync(out.toString());
}
