/* Writes lib/measure/named_colours.dart from test/fixtures/measure/named-colours.json
   (culori's colorsNamed), keeping culori's order: a tie goes to the first name, as it did. */
import 'dart:convert';
import 'dart:io';

void main() {
  final names = jsonDecode(File('test/fixtures/measure/named-colours.json').readAsStringSync()) as Map<String, dynamic>;
  final out = StringBuffer('// GENERATED by tool/named_colours_to_dart.dart — do not edit.\n')
    ..writeln('/* The 148 CSS named colours, in culori\'s order, as 0xRRGGBB. */')
    ..writeln('const namedColours = <String, int>{');
  names.forEach((k, v) => out.writeln("  '$k': 0x${(v as int).toRadixString(16).padLeft(6, '0').toUpperCase()},"));
  out.writeln('};');
  File('lib/measure/named_colours.dart').writeAsStringSync(out.toString());
}
